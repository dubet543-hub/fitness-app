function buildTotal(trainRaw, skillRaw) {
  const map = new Map();
  [...trainRaw, ...skillRaw].forEach(([label, dateStr, load]) => {
    const prev = map.get(dateStr) || [label, dateStr, 0];
    prev[2] += load;
    map.set(dateStr, prev);
  });
  return [...map.values()].sort((a,b) => new Date(a[1]) - new Date(b[1]));
}

