const alpha = 2/29;

function compute(rawData) {
  let chronic = 0;
  const runningLoads = [];
  const results = [];
  for (let i = 0; i < rawData.length; i++) {
    const [label, dateStr, load] = rawData[i];
    const date = new Date(dateStr);
    runningLoads.push(load);
    const cutoff = new Date(date); cutoff.setDate(cutoff.getDate() - 7);
    let sum7 = 0;
    for (let j = 0; j <= i; j++) {
      const d = new Date(rawData[j][1]);
      if (d > cutoff && d <= date) sum7 += rawData[j][2];
    }
    const acute = sum7 / 7;
    chronic = i === 0 ? acute : (acute * alpha) + (chronic * (1 - alpha));
    const n = runningLoads.length;
    const mean = runningLoads.reduce((a,b)=>a+b,0)/n;
    const sigma = n > 1 ? Math.sqrt(runningLoads.reduce((s,l)=>s+Math.pow(l-mean,2),0)/n) : 0;
    const acwr = chronic === 0 ? 0 : Math.round(acute/chronic*100)/100;
    const z    = sigma === 0  ? 0 : Math.round((load - chronic)/sigma*100)/100;
    results.push({ label, load, acute: Math.round(acute*10)/10, chronic: Math.round(chronic*10)/10, acwr, z });
  }
  return results;
}

function toDart(name, rows) {
  const lines = rows.map(r => `  _LP('${r.label}', ${r.load.toFixed(0)}, ${r.acute.toFixed(1)}, ${r.chronic.toFixed(1)}, ${r.acwr.toFixed(2)}, ${r.z.toFixed(2)}),`);
  return `const ${name} = <_LP>[\n${lines.join('\n')}\n];`;
}

